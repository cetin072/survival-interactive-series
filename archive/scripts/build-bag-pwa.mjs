// Deterministic checked-in integrity manifest; does not touch user data or deploy.
import {readFile,writeFile,readdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const root=new URL('../web/public/bag-lab/',import.meta.url);
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
const files=['alpha.html','alpha.css','manifest.webmanifest',...(await readdir(root)).filter(p=>p.endsWith('.mjs')&&p!=='app.mjs'),
  'reused/schedule-reminder-service.mjs','icons/bag-192.png','icons/bag-512.png','icons/bag-maskable-512.png'].sort();
// app.mjs is demo-only but cached to keep the static module inventory complete.
// Netlify Preview injects toolbar markup into .html. A generated plain-text source
// lets the worker verify canonical HTML without disabling site-wide processing.
const html=await readFile(new URL('alpha.html',root));
const canonical=new URL('alpha-shell.txt',root);
if(process.argv.includes('--check')){if(!(await readFile(canonical)).equals(html))throw new Error('BAG canonical HTML is stale');}
else await writeFile(canonical,html);
const assets=await Promise.all(files.map(async path=>({path,...(path==='alpha.html'?{source:'alpha-shell.txt'}:{}),sha256:sha(await readFile(new URL(path,root)))})));
const version=sha(JSON.stringify(assets)).slice(0,24);
const source='// Generated by archive/scripts/build-bag-pwa.mjs; do not hand edit.\nself.BAG_PWA_BUILD='+JSON.stringify({version,assets},null,2)+';\n';
const target=new URL('pwa-assets.js',root);
if(process.argv.includes('--check')){if(await readFile(target,'utf8')!==source)throw new Error('BAG shell changed: run node archive/scripts/build-bag-pwa.mjs');}
else await writeFile(target,source);
console.log('PASS BAG shell integrity cohort',version,assets.length,'assets');
